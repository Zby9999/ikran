const validatedKit1Snapshot = JSON.parse(fs.readFileSync(
  new URL(
    "../../docs/validation/question-card-plugin-candidate-2026-08-28.json",
    import.meta.url
  ),
  "utf8"
));
if (!Array.isArray(validatedKit1Snapshot.questions) ||
    validatedKit1Snapshot.questions.length !== KIT_1_OBSERVATIONS.length) {
  throw new Error("Validated Study Kit 1 Question snapshot must contain 16 cards");
}
const VALIDATED_KIT_1_QUESTION_CARDS = Object.freeze(
  validatedKit1Snapshot.questions.map((question, index) => card(
    question.section,
    KIT_1_OBSERVATIONS[index],
    question.question,
    question.options
  ))
);

export const STUDY_KIT_QUESTION_CARDS = Object.freeze({
  "kit-1": VALIDATED_KIT_1_QUESTION_CARDS,
  "kit-2": QUESTION_CARD_DRAFTS["kit-2"]
});

export function questionCardsForStudyKit(kitId) {
  const cards = STUDY_KIT_QUESTION_CARDS[kitId];
  if (!cards) throw new Error(`Unknown Study Kit question profile: ${kitId}`);
  return cards;
}
